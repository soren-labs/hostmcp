// Options selects a native service manager. A system service can run as any
// existing OS account. Installing it requires an already elevated process;
// HostMCP never elevates the installing process or grants the service account
// additional privileges.
type Options struct {
	System bool
	User   string
}

func InstallWithOptions(name, role, configPath string, options Options) error {
	if !options.System {
		if options.User != "" {
			return errors.New("--user requires --system; user services run as the installing account")
		}
		return Install(name, role, configPath)
	}
	return installSystem(name, role, configPath, options.User)
}

func UninstallWithOptions(name string, options Options) error {
	if options.User != "" {
		return errors.New("--user is only used when installing a system service")
	}
	if !options.System {
		return Uninstall(name)
	}
	if os.Geteuid() != 0 {
		return errors.New("system service removal requires root; run the command with sudo")
	}
	path, err := systemUnitPath(runtime.GOOS, name)
	if err != nil {
		return err
	}
	info, err := os.Lstat(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if !info.Mode().IsRegular() {
		return errors.New("refusing to remove a non-regular service file")
	}
	body, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if !strings.Contains(string(body), marker) {
		return errors.New("refusing to remove a service not generated by HostMCP")
	}
	if runtime.GOOS == "linux" {
		if err = run("systemctl", "disable", "--now", name+".service"); err != nil {
			return err
		}
	} else if err = stopLaunchd("system/com.hostmcp."+name, run, query); err != nil {
		return err
	}
	if err = os.Remove(path); err != nil {
		return err
	}
	if runtime.GOOS == "linux" {
		return run("systemctl", "daemon-reload")
	}
	return nil
}

type account struct {
	name, home, shell string
	uid, gid          uint32
	groups            []uint32
}

func lookupAccount(name string) (account, error) {
	if name == "" {
		name = "root"
	}
	u, err := user.Lookup(name)
	if err != nil {
		return account{}, fmt.Errorf("look up service user: %w", err)
	}
	uid, err := strconv.ParseUint(u.Uid, 10, 32)
	if err != nil {
		return account{}, err
	}
	gid, err := strconv.ParseUint(u.Gid, 10, 32)
	if err != nil {
		return account{}, err
	}
	groups, err := u.GroupIds()
	if err != nil {
		return account{}, fmt.Errorf("look up service groups: %w", err)
	}
	a := account{name: u.Username, home: u.HomeDir, shell: "/bin/sh", uid: uint32(uid), gid: uint32(gid)}
	for _, group := range groups {
		n, err := strconv.ParseUint(group, 10, 32)
		if err != nil {
			return account{}, err
		}
		a.groups = append(a.groups, uint32(n))
	}
	// NSS/macOS directory services are authoritative for login shell selection.
	// Accounts without a login shell still get /bin/sh as the process API default.
	if runtime.GOOS == "linux" {
		if out, err := exec.Command("getent", "passwd", u.Username).Output(); err == nil {
			fields := strings.Split(strings.TrimSpace(string(out)), ":")
			if len(fields) == 7 && filepath.IsAbs(fields[6]) {
				a.shell = fields[6]
			}
		}
	} else if runtime.GOOS == "darwin" {
		if out, err := exec.Command("dscl", ".", "-read", "/Users/"+u.Username, "UserShell").Output(); err == nil {
			if _, shell, ok := strings.Cut(strings.TrimSpace(string(out)), ": "); ok && filepath.IsAbs(shell) {
				a.shell = shell
			}
		}
	}
	if strings.HasSuffix(a.shell, "/nologin") || a.shell == "/bin/false" || a.shell == "/usr/bin/false" {
		a.shell = "/bin/sh"
	}
	return a, nil
}

func systemUnitPath(goos, name string) (string, error) {
	if !config.ValidID(name) || !strings.HasPrefix(name, "hostmcp-") {
		return "", errors.New("invalid HostMCP service name")
	}
	switch goos {
	case "linux":
		return filepath.Join("/etc/systemd/system", name+".service"), nil
	case "darwin":
		return filepath.Join("/Library/LaunchDaemons", "com.hostmcp."+name+".plist"), nil
	default:
		return "", errors.New("native services support Linux and macOS")
	}
}

func systemLogDir(name string) string {
	return filepath.Join("/Library/Logs/HostMCP", name)
}

func renderSystem(goos, name, role, binary, configPath string, a account) (string, error) {
	path := filepath.Join(a.home, ".local/bin") + ":/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
	if goos == "darwin" {
		path = "/opt/homebrew/bin:/opt/homebrew/sbin:" + path
	}
	body, err := Render(goos, name, role, binary, configPath, a.home, path)
	if err != nil {
		return "", err
	}
	body, err = withShell(goos, body, a.shell)
	if err != nil {
		return "", err
	}
	if strings.ContainsAny(a.name, "\r\n\x00") {
		return "", errors.New("invalid service account name")
	}
	if goos == "linux" {
		// The native manager sets the primary and supplementary groups for User=.
		body = strings.Replace(body, "Type=exec\n", fmt.Sprintf("Type=exec\nUser=%d\nGroup=%d\n", a.uid, a.gid), 1)
		body = strings.Replace(body, "WantedBy=default.target", "WantedBy=multi-user.target", 1)
		body = strings.Replace(body, "\nRestart=", "\nEnvironment="+unitQuote("USER="+a.name)+"\nEnvironment="+unitQuote("LOGNAME="+a.name)+"\nRestart=", 1)
	} else {
		body = strings.Replace(body, "<key>WorkingDirectory</key>", "<key>UserName</key><string>"+xmlText(a.name)+"</string>\n<key>WorkingDirectory</key>", 1)
		body = strings.Replace(body, "<key>HOME</key>", "<key>USER</key><string>"+xmlText(a.name)+"</string><key>LOGNAME</key><string>"+xmlText(a.name)+"</string><key>HOME</key>", 1)
		oldLog := filepath.Join(a.home, "Library", "Logs", "HostMCP", name+".log")
		body = strings.ReplaceAll(body, xmlText(oldLog), xmlText(filepath.Join(systemLogDir(name), "service.log")))
	}
	return body, nil
}

func checkAccountAccess(a account, operation, path string) error {
	cmd := exec.Command("/bin/test", operation, path)
	if a.uid != uint32(os.Geteuid()) || a.gid != uint32(os.Getegid()) {
		if runtime.GOOS == "darwin" {
			// Darwin directory-service memberships can exceed setgroups(2)'s
			// fixed-size list. Its native account helper initializes those groups
			// correctly. The installer is already root; this only drops authority.
			cmd = exec.Command("/usr/bin/sudo", "-n", "-u", "#"+strconv.FormatUint(uint64(a.uid), 10), "--", "/bin/test", operation, path)
		} else {
			cmd.SysProcAttr = &syscall.SysProcAttr{Credential: &syscall.Credential{Uid: a.uid, Gid: a.gid, Groups: a.groups}}
		}
	}
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("service user %s cannot access %s (%s); check ownership and parent directory permissions: %w", a.name, path, operation, err)
	}
	return nil
}

// A root service must not start from a binary or configuration replaceable by
// another OS account. This checks the resolved object and each parent directory.
func requireRootOwned(path string) error {
	for {
		info, err := os.Stat(path)
		if err != nil {
			return err
		}
		stat, ok := info.Sys().(*syscall.Stat_t)
		if !ok || stat.Uid != 0 || info.Mode().Perm()&0022 != 0 {
			return fmt.Errorf("root service requires a root-owned path without group/other write access: %s", path)
		}
		next := filepath.Dir(path)
		if next == path {
			return nil
		}
		path = next
	}
}

func installSystem(name, role, configPath, username string) error {
	if os.Geteuid() != 0 {
		return errors.New("system service installation requires root; run the command with sudo")
	}
	if name == "" {
		name = "hostmcp-" + role
	}
	unit, err := systemUnitPath(runtime.GOOS, name)
	if err != nil {
		return err
	}
	a, err := lookupAccount(username)
	if err != nil {
		return err
	}
	abs, err := filepath.Abs(configPath)
	if err != nil {
		return err
	}
	abs, err = filepath.EvalSymlinks(abs)
	if err != nil {
		return err
	}
	if role == "hub" {
		if _, err = config.NewStore(abs).Snapshot(); err != nil {
			return err
		}
	} else if role == "agent" {
		var a config.Agent
		if err = config.ReadJSON(abs, &a); err != nil {
			return err
		}
		if a.Version != config.FormatVersion || !config.ValidID(a.DeviceID) || len(a.Token) < 32 {
			return errors.New("invalid agent configuration")
		}
		if _, err = config.CheckURL(a.HubURL, a.AllowInsecure); err != nil {
			return err
		}
	} else {
		return errors.New("role must be hub or agent")
	}
	info, err := os.Stat(abs)
	if err != nil {
		return err
	}
	if stat, ok := info.Sys().(*syscall.Stat_t); !ok || stat.Uid != a.uid {
		return fmt.Errorf("configuration must be owned by service user %s (uid %d)", a.name, a.uid)
	}
	binary, err := os.Executable()
	if err != nil {
		return err
	}
	binary, err = filepath.EvalSymlinks(binary)
	if err != nil {
		return err
	}
	for _, check := range [][2]string{{"-r", abs}, {"-x", binary}, {"-x", a.home}} {
		if err = checkAccountAccess(a, check[0], check[1]); err != nil {
			return err
		}
	}
	if role == "hub" {
		if err = checkAccountAccess(a, "-w", filepath.Dir(abs)); err != nil {
			return err
		}
	}
	if a.uid == 0 {
		if err = requireRootOwned(binary); err != nil {
			return err
		}
		if err = requireRootOwned(abs); err != nil {
			return err
		}
	}
	body, err := renderSystem(runtime.GOOS, name, role, binary, abs, a)
	if err != nil {
		return err
	}
	if runtime.GOOS == "darwin" {
		if err = os.MkdirAll(filepath.Dir(systemLogDir(name)), 0755); err != nil {
			return err
		}
		if err = os.Mkdir(systemLogDir(name), 0700); err != nil && !os.IsExist(err) {
			return err
		}
		if err = os.Chown(systemLogDir(name), int(a.uid), int(a.gid)); err != nil {
			return err
		}
	}
	if err = config.WriteSecret(unit, []byte(body), false); err != nil {
		return err
	}
	// launchd requires a root-owned plist without group/other write permissions.
	if err = os.Chmod(unit, 0644); err != nil {
		return err
	}
	if runtime.GOOS == "linux" {
		err = startSystemdScoped(name, true, run, query)
	} else {
		if err = run("launchctl", "enable", "system/com.hostmcp."+name); err == nil {
			err = run("launchctl", "bootstrap", "system", unit)
		}
		if err == nil {
			time.Sleep(150 * time.Millisecond)
			var out []byte
			out, err = query("launchctl", "print", "system/com.hostmcp."+name)
			if err == nil && !strings.Contains(string(out), "state = running") {
				err = errors.New("launch daemon is loaded but not running; inspect its HostMCP service log")
			}
		}
	}
	if err != nil {
		return fmt.Errorf("service file saved at %s, but activation failed: %w", unit, err)
	}
	fmt.Fprintf(os.Stderr, "Installed system service %s as %s (uid %d): %s\n", name, a.name, a.uid, unit)
	return nil
}
